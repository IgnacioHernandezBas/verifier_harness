    def __init__(
        self,
        original_code: str,
        patched_code: str,
        changed_lines: List[int],
        function_name: str,
        function_params: List[Dict[str, Any]],
        class_name: Optional[str] = None,
        issue_description: str = "",
        patch_description: str = "",
        singularity_image: str = "/fs/nexus-scratch/ihbas/.containers/singularity/verifier-swebench.sif",
    ):
        """
        Initialize the Atheris-based differential fuzzer.

        Args:
            original_code: Python code before patch
            patched_code: Python code after patch
            changed_lines: Line numbers that were modified
            function_name: Name of function to test
            function_params: List of parameter specs [{'name': 'x', 'type': 'int'}, ...]
            class_name: Class name if testing a method
            issue_description: GitHub issue text (for classification)
            patch_description: Commit message (for classification)
            singularity_image: Path to Singularity container image
        """
        self.original_code = original_code
        self.patched_code = patched_code
        self.changed_lines = changed_lines
        self.function_name = function_name
        self.function_params = function_params
        self.class_name = class_name
        self.issue_description = issue_description.replace('"', '\\"').replace('\n', ' ')
        self.patch_description = patch_description.replace('"', '\\"').replace('\n', ' ')
        self.singularity_image = Path(singularity_image)

    def _generate_input_code(self) -> Tuple[str, str]:
        """
        Generate code to convert Atheris bytes to structured input.

        Returns:
            (atheris_code, fallback_code) - code for both Atheris and fallback modes
        """
        atheris_lines = []
        fallback_parts = []

        for param in self.function_params:
            name = param['name']
            ptype = param.get('type', 'any').lower()
            default = param.get('default')

            # Note: 12 spaces indentation to align inside atheris_test function
            indent = "            "
            if ptype in ('int', 'integer'):
                atheris_lines.append(f"{indent}input_data['{name}'] = fdp.ConsumeInt(4)")
                fallback_parts.append(f"'{name}': random.randint(-100, 100)")
            elif ptype in ('float', 'double'):
                atheris_lines.append(f"{indent}input_data['{name}'] = fdp.ConsumeFloat()")
                fallback_parts.append(f"'{name}': random.uniform(-100.0, 100.0)")
            elif ptype in ('str', 'string'):
                atheris_lines.append(f"{indent}input_data['{name}'] = fdp.ConsumeString(fdp.ConsumeIntInRange(0, 50))")
                fallback_parts.append(f"'{name}': ''.join(random.choices('abcdefghij', k=random.randint(0, 10)))")
            elif ptype in ('bool', 'boolean'):
                atheris_lines.append(f"{indent}input_data['{name}'] = fdp.ConsumeBool()")
                fallback_parts.append(f"'{name}': random.choice([True, False])")
            elif ptype in ('list', 'array'):
                atheris_lines.append(f"{indent}_len = fdp.ConsumeIntInRange(0, 20)")
                atheris_lines.append(f"{indent}input_data['{name}'] = [fdp.ConsumeInt(4) for _ in range(_len)]")
                fallback_parts.append(f"'{name}': [random.randint(-10, 10) for _ in range(random.randint(0, 10))]")
            elif 'optional' in ptype or default is None:
                # Optional parameter - sometimes None, sometimes a value
                atheris_lines.append(f"{indent}if fdp.ConsumeBool():")
                atheris_lines.append(f"{indent}    input_data['{name}'] = fdp.ConsumeInt(4)")
                atheris_lines.append(f"{indent}else:")
                atheris_lines.append(f"{indent}    input_data['{name}'] = None")
                fallback_parts.append(f"'{name}': random.choice([None, random.randint(0, 10)])")
            else:
                # Generic fallback
                atheris_lines.append(f"{indent}input_data['{name}'] = fdp.ConsumeInt(4)")
                fallback_parts.append(f"'{name}': random.randint(-100, 100)")

        atheris_code = '\n'.join(atheris_lines) if atheris_lines else "            pass"
        fallback_code = '{' + ', '.join(fallback_parts) + '}' if fallback_parts else '{}'

        return atheris_code, fallback_code

    def _generate_harness(self, max_iterations: int, timeout_per_input: float) -> str:
        """Generate the fuzzing harness code."""
        atheris_code, fallback_code = self._generate_input_code()

        harness = self.HARNESS_TEMPLATE.format(
            changed_lines=self.changed_lines,
            function_name=self.function_name,
            class_name_repr=repr(self.class_name),
            max_iterations=max_iterations,
            input_generation_code_atheris=atheris_code,
            gen_fallback_input=fallback_code,
            issue_description=self.issue_description,
            patch_description=self.patch_description,
        )

        return harness

    def fuzz(
        self,
        max_iterations: int = 10000,
        timeout_seconds: float = 300.0,
        timeout_per_input: float = 5.0,
    ) -> AtherisFuzzingResult:
        """
        Run coverage-guided differential fuzzing in a container.

        Args:
            max_iterations: Maximum number of inputs to test
            timeout_seconds: Total fuzzing time limit
            timeout_per_input: Timeout for each individual input

        Returns:
            AtherisFuzzingResult with all findings
        """
        start_time = time.time()

        with tempfile.TemporaryDirectory() as tmpdir:
            tmpdir_path = Path(tmpdir)

            # Create directory structure
            original_dir = tmpdir_path / "original"
            patched_dir = tmpdir_path / "patched"
            original_dir.mkdir()
            patched_dir.mkdir()

            # Write original code
            (original_dir / "original_module.py").write_text(self.original_code)
            (original_dir / "__init__.py").write_text("")

            # Write patched code
            (patched_dir / "patched_module.py").write_text(self.patched_code)
            (patched_dir / "__init__.py").write_text("")

            # Generate and write fuzzing harness
            harness_code = self._generate_harness(max_iterations, timeout_per_input)
            harness_file = tmpdir_path / "fuzz_harness.py"
            harness_file.write_text(harness_code)

            # Make harness executable
            harness_file.chmod(0o755)

            # Run in Singularity container
            result = self._run_in_container(tmpdir_path, timeout_seconds)

            elapsed = time.time() - start_time

            # Parse results
            results_file = tmpdir_path / "fuzzing_results.json"
            if results_file.exists():
                results_data = json.loads(results_file.read_text())
            else:
                results_data = {
                    'total_inputs': 0,
                    'divergences': [],
                    'expected_divergences': 0,
                    'suspicious_divergences': 0,
                    'regressions': 0,
                    'changed_line_coverage': 0.0,
                    'covered_changed_lines': [],
                    'uncovered_changed_lines': self.changed_lines,
                }

            # Convert divergences to DifferentialResult objects
            divergences = []
            for d in results_data.get('divergences', []):
                div_type = DivergenceType(d['divergence_type']) if d.get('divergence_type') else None
                classification = ChangeClassification(d['classification']) if d.get('classification') else None

                divergences.append(DifferentialResult(
                    input_data=d.get('input', {}),
                    original_result=d.get('original_result'),
                    original_exception=d.get('original_exception'),
                    patched_result=d.get('patched_result'),
                    patched_exception=d.get('patched_exception'),
                    original_covered_lines=set(d.get('original_covered', [])),
                    patched_covered_lines=set(d.get('patched_covered', [])),
                    is_divergent=True,
                    divergence_type=div_type,
                    classification=classification,
                    explanation=d.get('explanation', ''),
                ))

            # Determine verdict
            regressions = results_data.get('regressions', 0)
            suspicious = results_data.get('suspicious_divergences', 0)
            coverage = results_data.get('changed_line_coverage', 0.0)

            if regressions > 0:
                verdict = "FAIL"
                verdict_explanation = f"Found {regressions} regression(s)"
            elif suspicious > 5:
                verdict = "WARNING"
                verdict_explanation = f"Found {suspicious} suspicious changes"
            elif coverage < 0.5:
                verdict = "WARNING"
                verdict_explanation = f"Low coverage ({coverage:.0%})"
            else:
                verdict = "PASS"
                verdict_explanation = f"No regressions, {coverage:.0%} coverage"

            return AtherisFuzzingResult(
                total_inputs=results_data.get('total_inputs', 0),
                unique_crashes=0,  # TODO: track unique crashes
                divergences=divergences,
                expected_divergences=results_data.get('expected_divergences', 0),
                suspicious_divergences=results_data.get('suspicious_divergences', 0),
                regressions=regressions,
                changed_line_coverage=coverage,
                covered_changed_lines=results_data.get('covered_changed_lines', []),
                uncovered_changed_lines=results_data.get('uncovered_changed_lines', []),
                corpus_size=0,  # TODO: track corpus
                fuzzing_duration_seconds=elapsed,
                verdict=verdict,
                verdict_explanation=verdict_explanation,
            )

    def _run_in_container(self, work_dir: Path, timeout: float) -> subprocess.CompletedProcess:
        """Run the fuzzing harness in a Singularity container with Atheris support."""
        # Atheris library location (installed per-instance)
        atheris_lib_path = "/fs/nexus-scratch/ihbas/.cache/atheris_lib"

        cmd = [
            'singularity', 'exec',
            '--bind', f'{work_dir}:/workspace',
            '--bind', f'{atheris_lib_path}:/tmp/atheris_lib',
            '--pwd', '/workspace',
            '--env', 'PYTHONPATH=/tmp/atheris_lib:$PYTHONPATH',
            str(self.singularity_image),
            'python', '/workspace/fuzz_harness.py',
        ]

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=timeout + 30,  # Extra buffer for cleanup
                cwd=work_dir,
            )
            # Print container output for debugging
            if result.stdout:
                print(f"Container stdout: {result.stdout[:500]}")
            if result.stderr:
                print(f"Container stderr: {result.stderr[:500]}")
            if result.returncode != 0:
                print(f"Container exit code: {result.returncode}")
            return result
        except subprocess.TimeoutExpired:
            print(f"Fuzzing timeout after {timeout}s")
            return subprocess.CompletedProcess(cmd, 1, "", "TIMEOUT")
        except Exception as e:
            print(f"Fuzzing error: {e}")
            return subprocess.CompletedProcess(cmd, 1, "", str(e))

    def generate_report(self, result: AtherisFuzzingResult) -> str:
        """Generate a human-readable report."""
        lines = [
            "=" * 80,
            "ATHERIS COVERAGE-GUIDED DIFFERENTIAL FUZZING REPORT",
            "=" * 80,
            "",
            f"Function: {self.class_name + '.' if self.class_name else ''}{self.function_name}",
            f"Changed Lines: {self.changed_lines}",
            "",
            "--- COVERAGE ---",
            f"Changed Line Coverage: {result.changed_line_coverage:.1%}",
            f"Covered: {result.covered_changed_lines}",
            f"NOT Covered: {result.uncovered_changed_lines}",
            "",
            "--- FUZZING STATS ---",
            f"Total Inputs: {result.total_inputs}",
            f"Duration: {result.fuzzing_duration_seconds:.1f}s",
            f"Throughput: {result.total_inputs / max(result.fuzzing_duration_seconds, 0.1):.0f} inputs/sec",
            "",
            "--- DIVERGENCES ---",
            f"Total: {len(result.divergences)}",
            f"  Expected: {result.expected_divergences}",
            f"  Suspicious: {result.suspicious_divergences}",
            f"  REGRESSIONS: {result.regressions}",
            "",
        ]

        if result.divergences:
            lines.append("--- DIVERGENCE DETAILS ---")
            for i, div in enumerate(result.divergences[:10], 1):
                lines.extend([
                    f"",
                    f"[{i}] {div.classification.value.upper() if div.classification else 'UNKNOWN'}",
                    f"    Input: {div.input_data}",
                    f"    Original: {div.original_exception or div.original_result}",
                    f"    Patched:  {div.patched_exception or div.patched_result}",
                    f"    {div.explanation}",
                ])

        lines.extend([
            "",
            "--- VERDICT ---",
            f"  {result.verdict}: {result.verdict_explanation}",
            "",
            "=" * 80,
        ])

        return "\n".join(lines)



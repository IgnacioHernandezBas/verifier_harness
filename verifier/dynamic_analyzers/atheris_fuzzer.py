class DivergenceType(Enum):
    """Classification of behavioral divergences."""
    EXPECTED_FIX = "expected_fix"
    EXPECTED_SIDE_EFFECT = "expected_side_effect"
    SUSPICIOUS = "suspicious"
    REGRESSION = "regression"
    PERFORMANCE = "performance_regression"


class ChangeClassification(Enum):
    """Classification of whether a behavioral change is expected."""
    EXPECTED = "expected"
    SUSPICIOUS = "suspicious"
    REGRESSION = "regression"


@dataclass
class DifferentialResult:
    """Result of comparing original vs patched execution."""
    input_data: Dict[str, Any]
    original_result: Any
    original_exception: Optional[str]
    patched_result: Any
    patched_exception: Optional[str]
    original_covered_lines: Set[int]
    patched_covered_lines: Set[int]
    is_divergent: bool
    divergence_type: Optional[DivergenceType] = None
    classification: Optional[ChangeClassification] = None
    explanation: str = ""

    def to_dict(self) -> Dict:
        return {
            'input_data': self.input_data,
            'original_result': str(self.original_result),
            'original_exception': self.original_exception,
            'patched_result': str(self.patched_result),
            'patched_exception': self.patched_exception,
            'original_covered_lines': list(self.original_covered_lines),
            'patched_covered_lines': list(self.patched_covered_lines),
            'is_divergent': self.is_divergent,
            'divergence_type': self.divergence_type.value if self.divergence_type else None,
            'classification': self.classification.value if self.classification else None,
            'explanation': self.explanation,
        }


@dataclass
class AtherisFuzzingResult:
    """Complete result of Atheris-based differential fuzzing."""
    total_inputs: int
    unique_crashes: int
    divergences: List[DifferentialResult]
    expected_divergences: int
    suspicious_divergences: int
    regressions: int
    changed_line_coverage: float
    covered_changed_lines: List[int]
    uncovered_changed_lines: List[int]
    corpus_size: int
    fuzzing_duration_seconds: float
    verdict: str
    verdict_explanation: str

    def to_dict(self) -> Dict:
        return {
            'total_inputs': self.total_inputs,
            'unique_crashes': self.unique_crashes,
            'divergences': [d.to_dict() for d in self.divergences],
            'expected_divergences': self.expected_divergences,
            'suspicious_divergences': self.suspicious_divergences,
            'regressions': self.regressions,
            'changed_line_coverage': self.changed_line_coverage,
            'covered_changed_lines': self.covered_changed_lines,
            'uncovered_changed_lines': self.uncovered_changed_lines,
            'corpus_size': self.corpus_size,
            'fuzzing_duration_seconds': self.fuzzing_duration_seconds,
            'verdict': self.verdict,
            'verdict_explanation': self.verdict_explanation,
        }



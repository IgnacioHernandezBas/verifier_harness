"""
Atheris-Based Coverage-Guided Differential Fuzzer for Patch Verification.

This module implements TRUE coverage-guided fuzzing using Google's Atheris library.
Unlike Hypothesis (which generates random inputs within type constraints), Atheris
uses coverage feedback to actively seek inputs that hit new code paths.

ARCHITECTURE:
1. Write original and patched code to files in temp directories
2. Generate an Atheris fuzzing harness that:
   - Takes byte input from Atheris
   - Converts bytes to structured input using FuzzedDataProvider
   - Runs both original and patched versions
   - Compares results (differential oracle)
   - Reports coverage back to Atheris
3. Run the harness in a Singularity container
4. Collect results and classify behavioral differences

KEY DIFFERENTIATORS FROM EXISTING WORK:
- vs PATCH-SIM: Coverage-guided input generation (not random)
- vs Opad: Detects logic bugs (not just crashes), classifies changes
- vs FuzzRepair: Verifies external patches (not generates patches)
- vs UTBoost: Deterministic, no LLM dependency
"""


def classify_divergence(orig_exc, patch_exc, orig_result, patch_result):
    """Classify behavioral divergence."""
    issue_lower = ISSUE_DESC.lower()
    patch_lower = PATCH_DESC.lower()
    combined_desc = issue_lower + " " + patch_lower

    if orig_exc != patch_exc:
        if orig_exc and not patch_exc:
            # Original raised, patched doesn't - likely fix
            return "expected_fix", "expected", f"Patch fixes {{orig_exc}}"
        elif not orig_exc and patch_exc:
            # Regression - was working, now fails
            return "regression", "regression", f"REGRESSION: Was working, now raises {{patch_exc}}"
        else:
            # Different exception types - usually expected when improving error handling
            # Check if it's a common error handling improvement pattern
            error_improvements = [
                ('zerodivision', 'value'),  # ZeroDivisionError -> ValueError
                ('index', 'value'),          # IndexError -> ValueError
                ('key', 'value'),            # KeyError -> ValueError
                ('type', 'value'),           # TypeError -> ValueError
                ('attribute', 'value'),      # AttributeError -> ValueError
            ]
            orig_lower = orig_exc.lower() if orig_exc else ""
            patch_lower_exc = patch_exc.lower() if patch_exc else ""

            # Check if this is a common error handling improvement
            is_improvement = any(
                orig_lower.startswith(old) and patch_lower_exc.startswith(new)
                for old, new in error_improvements
            )

            # Also check if description mentions fixing/handling errors
            fix_keywords = ['fix', 'handle', 'error', 'exception', 'zero', 'crash', 'fail']
            desc_mentions_fix = any(kw in combined_desc for kw in fix_keywords)

            if is_improvement or desc_mentions_fix:
                return "expected_fix", "expected", f"Exception improved: {{orig_exc}} -> {{patch_exc}}"
            return "suspicious", "suspicious", f"Exception changed: {{orig_exc}} -> {{patch_exc}}"

    elif orig_result != patch_result:
        fix_keywords = ['fix', 'correct', 'handle', 'return', 'change', 'update', 'improve']
        if any(kw in combined_desc for kw in fix_keywords):
            return "expected_side_effect", "expected", f"Result changed (expected)"
        return "expected_side_effect", "suspicious", f"Result changed unexpectedly"

    return None, None, ""

def run_differential_test(input_data):
    """Run one differential test."""
    global total_inputs, divergences, covered_changed_lines
    total_inputs += 1

    # Run original
    try:
        if CLASS_NAME:
            cls = getattr(original_module, CLASS_NAME)
            if FUNCTION_NAME == "__init__":
                orig_result = cls(**input_data)
            else:
                instance = cls()
                orig_result = getattr(instance, FUNCTION_NAME)(**input_data)
        else:
            orig_result = getattr(original_module, FUNCTION_NAME)(**input_data)
        orig_exc = None
    except Exception as e:
        orig_result = None
        orig_exc = type(e).__name__

    # Run patched
    try:
        if CLASS_NAME:
            cls = getattr(patched_module, CLASS_NAME)
            if FUNCTION_NAME == "__init__":
                patch_result = cls(**input_data)
            else:
                instance = cls()
                patch_result = getattr(instance, FUNCTION_NAME)(**input_data)
        else:
            patch_result = getattr(patched_module, FUNCTION_NAME)(**input_data)
        patch_exc = None
    except Exception as e:
        patch_result = None
        patch_exc = type(e).__name__

    # Check for divergence
    is_divergent = (orig_exc != patch_exc) or (orig_exc is None and orig_result != patch_result)

    if is_divergent:
        div_type, classification, explanation = classify_divergence(
            orig_exc, patch_exc, orig_result, patch_result
        )
        if div_type:
            divergences.append({{
                'input': input_data,
                'original_result': str(orig_result),
                'original_exception': orig_exc,
                'patched_result': str(patch_result),
                'patched_exception': patch_exc,
                'divergence_type': div_type,
                'classification': classification,
                'explanation': explanation,
            }})
            # Mark changed lines as covered (simplified - assumes divergence means we hit changed code)
            covered_changed_lines.update(CHANGED_LINES[:2])  # Conservative estimate
            print(f"Divergence: {{input_data}} -> orig={{orig_exc or orig_result}}, patch={{patch_exc or patch_result}}")

            # Save results immediately after each divergence for crash safety
            save_results()
            return True

    return False

def save_results():
    """Save results to JSON file - called after each divergence for crash safety."""
    changed_set = set(CHANGED_LINES)
    uncovered = changed_set - covered_changed_lines
    coverage_pct = len(covered_changed_lines) / len(changed_set) if changed_set else 1.0

    expected = sum(1 for d in divergences if d.get('classification') == 'expected')
    suspicious = sum(1 for d in divergences if d.get('classification') == 'suspicious')
    regressions = sum(1 for d in divergences if d.get('classification') == 'regression')

    results = {{
        'total_inputs': total_inputs,
        'divergences': divergences,
        'expected_divergences': expected,
        'suspicious_divergences': suspicious,
        'regressions': regressions,
        'changed_line_coverage': coverage_pct,
        'covered_changed_lines': list(covered_changed_lines),
        'uncovered_changed_lines': list(uncovered),
    }}

    # Write atomically to prevent corruption
    temp_file = results_file.with_suffix('.tmp')
    temp_file.write_text(json.dumps(results, indent=2))
    temp_file.replace(results_file)

    if total_inputs % 50 == 0:  # Print every 50 inputs to avoid spam
        print(f"Progress: {{total_inputs}} inputs, {{len(divergences)}} divergences")

